-- PC Pricing Tracker: PostgreSQL schema (Supabase).
-- Idempotent: safe to run again. Apply with `python -m tracker.db init`.
--
-- Prices are append-only: a snapshot row is never updated in place, so the history
-- cannot be silently rewritten. The tracker writes as the `postgres` role (which
-- bypasses row level security); the dashboard reads through the Data API as `anon`,
-- which is given SELECT only at the bottom of this file.

create table if not exists brands (
    name            text primary key,              -- Best Buy's brand facet spelling; maintained by hand
    enabled         boolean not null default true
);

create table if not exists products (
    sku                 text primary key,          -- Best Buy SKU: one offer of a product
    bsin                text,                      -- product id in /product/<slug>/<BSIN> URLs
    upc                 text,
    url                 text not null,
    title               text not null,
    brand               text,                      -- as listed by Best Buy (may be a sub-brand: "HP OMEN")
    seller_class        text not null default '1P',   -- 1P = sold by Best Buy, 3P = Marketplace seller
    condition           text not null default 'new',  -- new | open-box | refurbished | pre-owned
    open_box_condition  text,
    categories          text[] not null default '{}',
    raw_specs           jsonb,                     -- untouched spec table, for re-normalising without scraping
    rank                int,                       -- position in Best Buy's best-selling order when crawled
    first_seen          timestamptz not null default now(),
    last_seen           timestamptz not null default now(),
    pinned              boolean not null default false, -- added by URL: always tracked, its group always featured
    active              boolean not null default true,  -- false after repeated not-found answers
    miss_count          int not null default 0
);

create table if not exists product_specs (
    sku             text primary key references products(sku) on delete cascade,
    brand           text,                          -- maker, sub-brands folded in ("HP OMEN" -> "HP")
    model_family    text,
    model_number    text,                          -- manufacturer part number
    cpu_model       text,                          -- identity: vendor-modelnumber, e.g. intel-226v
    cpu_name        text,                          -- display, e.g. Intel Core Ultra 5 226V
    cpu_class       text,                          -- family + tier + generation, e.g. intel-core-ultra-5-s2
    memory_gb       int,
    storage_gb      int,                           -- 1 TB is stored as 1024
    storage_type    text,                          -- ssd | emmc | ufs | hdd | hybrid
    form_factor     text,                          -- clamshell | convertible | detachable | dual-screen
    touchscreen     boolean,
    os              text,                          -- windows | chromeos | macos | googlebook | linux | ...
    os_edition      text,
    gpu             text,                          -- integrated | nvidia-rtx-5060 | ...
    gpu_name        text,
    screen_size_in  numeric(4,1),
    screen_bucket   text,                          -- ≤13 | 14 | 15–16 | 17+ (compared at the strict level only)
    resolution      text,
    color           text,
    group_key       text,                          -- exact level; null until every key field parsed
    strict_key      text,                          -- null as well when the screen size is unknown
    relaxed_key     text,
    class_key       text,
    needs_review    boolean not null default false,
    review_notes    text[] not null default '{}',
    normaliser_ver  text not null,
    updated_at      timestamptz not null default now()
);
-- Added with the strict level: a database created before it gets the columns here.
alter table product_specs add column if not exists screen_bucket text;
alter table product_specs add column if not exists strict_key    text;
create index if not exists product_specs_group_key_idx   on product_specs (group_key);
create index if not exists product_specs_strict_key_idx  on product_specs (strict_key);
create index if not exists product_specs_relaxed_key_idx on product_specs (relaxed_key);
create index if not exists product_specs_class_key_idx   on product_specs (class_key);

-- Generated by build_groups.py, rewritten in full on every run. One row per group per match
-- level; group_key matches product_specs.strict_key / group_key / relaxed_key / class_key.
create table if not exists spec_groups (
    group_key        text primary key,
    level            text not null,                -- strict | exact | relaxed | class (checked below)
    label            text not null,
    cpu              text,                         -- cpu_model (strict, exact, relaxed) or cpu_class (class)
    memory_gb        int,
    storage_gb       int,
    storage_type     text,                         -- null where the level ignores it
    form_factor      text,
    touchscreen      boolean,                      -- null where the level ignores it
    screen_bucket    text,                         -- strict level only
    os               text,
    gpu              text,
    member_count     int not null default 0,
    brand_count      int not null default 0,
    competitor_count int not null default 0,       -- brands other than the anchor
    brands           text[] not null default '{}',
    has_anchor       boolean not null default false,
    tracked          boolean not null default false,  -- has_anchor and competitor_count >= MIN_COMPETITORS
    featured_rank    int,                          -- 1..N for the headline groups, else null
    created_at       timestamptz not null default now()
);
alter table spec_groups add column if not exists screen_bucket text;
-- The list of levels grew: the check is replaced on every run, not only set at creation.
alter table spec_groups drop constraint if exists spec_groups_level_check;
alter table spec_groups add constraint spec_groups_level_check
    check (level in ('strict', 'exact', 'relaxed', 'class'));
create index if not exists spec_groups_level_idx on spec_groups (level, tracked);

create table if not exists scrape_runs (
    id              bigint primary key,            -- made by the job (epoch ms) so an offline run keeps its id
    started_at      timestamptz not null,
    finished_at     timestamptz,
    source          text not null,
    kind            text,                          -- collect | prices | backfill | add
    products_ok     int default 0,
    products_failed int default 0,
    status          text,                          -- ok | partial | failed
    error           text
);

create table if not exists price_snapshots (
    id              bigint generated always as identity primary key,
    sku             text not null references products(sku),
    snapshot_date   date not null,                 -- UTC date of the observation
    price           numeric(10,2) not null,        -- what the customer pays
    list_price      numeric(10,2),
    in_stock        boolean,
    source          text not null,                 -- bestbuy_graphql | honey | honey_carried | shopsavvy | shopsavvy_carried
    flagged         boolean not null default false,-- failed the sanity check: stored, not charted
    captured_at     timestamptz not null default now(),
    run_id          bigint,
    unique (sku, snapshot_date, source)
);
create index if not exists price_snapshots_sku_date_idx on price_snapshots (sku, snapshot_date);

-- ---------------------------------------------------------------------------------
-- Views. security_invoker makes each view obey the caller's grants and policies.

-- First-hand prices only: what this tracker's own scraper observed.
create or replace view prices_own with (security_invoker = true) as
select sku, snapshot_date, price, list_price, in_stock, source
from price_snapshots
where source = 'bestbuy_graphql' and not flagged;

-- One price per SKU per day, choosing the most trusted source.
create or replace view daily_prices with (security_invoker = true) as
select distinct on (sku, snapshot_date)
       sku, snapshot_date, price, list_price, in_stock, source
from price_snapshots
where not flagged
  and source in ('bestbuy_graphql', 'honey', 'honey_carried', 'shopsavvy', 'shopsavvy_carried')
order by sku, snapshot_date,
         case source when 'bestbuy_graphql'   then 1
                     when 'honey'             then 2
                     when 'honey_carried'     then 3
                     when 'shopsavvy'         then 4
                     else 5 end;

-- Which laptops belong to which group, at every match level. Only New offers sold
-- by Best Buy count, exactly as in tracker/grouping.py.
create or replace view group_members with (security_invoker = true) as
select g.group_key, g.level, s.sku
from spec_groups g
join product_specs s
  on (g.level = 'strict'  and s.strict_key  = g.group_key)
  or (g.level = 'exact'   and s.group_key   = g.group_key)
  or (g.level = 'relaxed' and s.relaxed_key = g.group_key)
  or (g.level = 'class'   and s.class_key   = g.group_key)
join products p on p.sku = s.sku
where p.active and p.seller_class = '1P' and p.condition = 'new';

-- SKUs the daily job fetches: members of tracked groups, plus pinned products.
create or replace view tracked_skus with (security_invoker = true) as
select p.sku
from products p
where p.active
  and (p.pinned
       or exists (select 1
                  from group_members m
                  join spec_groups g on g.group_key = m.group_key
                  where m.sku = p.sku and g.tracked));

-- ---------------------------------------------------------------------------------
-- Read-only access for the dashboard (Supabase Data API roles). Skipped on a plain
-- PostgreSQL server, where these roles do not exist.
do $$
declare
    t text;
begin
    if not exists (select 1 from pg_roles where rolname = 'anon') then
        return;
    end if;
    foreach t in array array['brands', 'products', 'product_specs', 'spec_groups',
                             'scrape_runs', 'price_snapshots'] loop
        execute format('alter table public.%I enable row level security', t);
        execute format('revoke all on table public.%I from anon, authenticated', t);
        execute format('grant select on table public.%I to anon, authenticated', t);
        execute format('drop policy if exists "read only" on public.%I', t);
        execute format('create policy "read only" on public.%I for select to anon, authenticated using (true)', t);
    end loop;
    foreach t in array array['prices_own', 'daily_prices', 'group_members', 'tracked_skus'] loop
        execute format('revoke all on table public.%I from anon, authenticated', t);
        execute format('grant select on table public.%I to anon, authenticated', t);
    end loop;
end
$$;
